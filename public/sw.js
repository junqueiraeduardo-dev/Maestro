/*
 * Service worker simples: permite instalar como app e abrir mesmo
 * com internet ruim. Sempre tenta a rede primeiro (assim as
 * atualizações aparecem logo) e usa o cache só se estiver offline.
 * Se mudar algo grande, troque a versão abaixo.
 */
const CACHE = 'dra-lara-v1';

self.addEventListener('install', () => self.skipWaiting());

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((chaves) => Promise.all(chaves.filter((c) => c !== CACHE).map((c) => caches.delete(c)))).then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(
    fetch(req)
      .then((resp) => {
        if (resp.ok) {
          const copia = resp.clone();
          caches.open(CACHE).then((c) => c.put(req, copia));
        }
        return resp;
      })
      .catch(() => caches.match(req).then((r) => r || caches.match('/'))),
  );
});
